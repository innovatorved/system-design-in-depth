/* ═══════════════════════════════════════════════════════════════
   Lazy loader for per-module data (lesson content + question banks).
   window.LAZY_MANIFEST ({path: hash}) is generated by tools/stamp-assets.js,
   so every file is fetched as path?v=<hash> and can be cached as immutable.
   ═══════════════════════════════════════════════════════════════ */

window.Lazy = (() => {
  const manifest = () => window.LAZY_MANIFEST || {};
  const pending = new Map();

  function load(path, fallbackPath) {
    if (pending.has(path)) return pending.get(path);
    const resolvedFallback = fallbackPath || (
      path.startsWith('https://cdn.jsdelivr.net/npm/@innovatorved/code-lab')
        ? path.replace('https://cdn.jsdelivr.net/npm/', 'https://unpkg.com/')
        : null
    );
    const p = new Promise((resolve, reject) => {
      const s = document.createElement('script');
      s.src = path + (manifest()[path] ? '?v=' + manifest()[path] : '');
      if (/^https?:\/\//.test(path)) s.crossOrigin = 'anonymous';
      s.onload = () => resolve();
      s.onerror = () => {
        if (resolvedFallback) {
          const fb = document.createElement('script');
          fb.src = resolvedFallback;
          if (/^https?:\/\//.test(resolvedFallback)) fb.crossOrigin = 'anonymous';
          fb.onload = () => resolve();
          fb.onerror = () => {
            const ghMatch = path.match(/^https:\/\/cdn\.jsdelivr\.net\/npm\/@innovatorved\/code-lab@([^/]+)\/(.+)$/);
            if (ghMatch) {
              const ghFb = document.createElement('script');
              ghFb.src = `https://cdn.jsdelivr.net/gh/innovatorved/code-lab@v${ghMatch[1]}/${ghMatch[2]}`;
              ghFb.crossOrigin = 'anonymous';
              ghFb.onload = () => resolve();
              ghFb.onerror = () => { pending.delete(path); reject(new Error('Failed to load ' + path + ' (and fallbacks)')); };
              document.head.appendChild(ghFb);
              return;
            }
            pending.delete(path);
            reject(new Error('Failed to load ' + path + ' (and fallback ' + resolvedFallback + ')'));
          };
          document.head.appendChild(fb);
          return;
        }
        pending.delete(path);
        reject(new Error('Failed to load ' + path));
      };
      document.head.appendChild(s);
    });
    pending.set(path, p);
    return p;
  }

  // Content (mNN-*.js) and questions (qNN-*.js) for a module number like "05"
  function module(number) {
    const prefixes = [`data/content/m${number}-`, `data/questions/q${number}-`];
    const files = Object.keys(manifest()).filter(f => prefixes.some(p => f.startsWith(p)));
    return Promise.all(files.map(load));
  }

  window.loadScript = load;
  return { load, module };
})();

